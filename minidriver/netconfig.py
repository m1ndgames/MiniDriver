"""Home-network configuration: derive the WPA-PSK and render the wpa_supplicant
file the daemon uses to associate.

Ported from m1ndb0x, with one deliberate difference: m1ndb0x handed the file to
systemd's wpa_supplicant@ and let it own the radio for the whole uptime. Here the
daemon owns the single radio directly -- it scans in the field and only brings up
an association when a home network is in range -- so this module renders and
writes the config, and station.py starts and stops wpa_supplicant against it.

The passphrase need never be written in clear: `psk_hash` derives the key that
goes into the file, and a config may carry a precomputed `psk_hash` so the
passphrase stays off the box entirely. (The derived key still grants full access
to the network, so the file is a 0600 secret either way -- the win is keeping a
reused human passphrase out of a file.)
"""
import hashlib
import logging
import re
from pathlib import Path

log = logging.getLogger(__name__)

SUPPLICANT_HEADER = """\
# Generated by minidriver from config.yaml -- edits here are overwritten.
# Home networks live under `network.home_networks`.
ctrl_interface=DIR=/run/wpa_supplicant GROUP=netdev
update_config=0
"""

# wpa_supplicant takes an SSID as a quoted string with no escaping worth relying
# on, so anything that could close the quote or open a new block is removed. An
# SSID is copied off the air and is not ours to trust.
UNSAFE = re.compile(r'["\n\r{}]')


def psk_hash(ssid: str, passphrase: str) -> str:
    """The WPA-PSK for a passphrase on a network.

    PBKDF2-HMAC-SHA1, the SSID as salt, 4096 iterations, 32 bytes -- the
    derivation from IEEE 802.11i.
    """
    return hashlib.pbkdf2_hmac(
        "sha1", passphrase.encode("utf-8"), ssid.encode("utf-8"), 4096, 32).hex()


def _clean(value: str) -> str:
    return UNSAFE.sub("", str(value))


def render_supplicant_conf(networks, country=None) -> str:
    """Render the whole supplicant config for the home networks."""
    lines = [SUPPLICANT_HEADER]
    if country:
        lines.append(f"country={_clean(country)}\n")

    for entry in networks or []:
        ssid = (entry or {}).get("ssid")
        if not ssid:
            # A silently skipped network looks identical to a wrong passphrase
            # from the outside, so refuse loudly instead.
            raise ValueError(f"home network without an ssid: {entry!r}")
        ssid = _clean(ssid)
        block = ["network={", f'    ssid="{ssid}"']

        key = entry.get("psk_hash")
        if not key and entry.get("psk"):
            key = psk_hash(ssid, entry["psk"])
        if key:
            # Unquoted: a bare 64-hex value is the derived key, a quoted one
            # would be a passphrase.
            block.append(f"    psk={_clean(key)}")
        else:
            block.append("    key_mgmt=NONE")

        if entry.get("priority") is not None:
            block.append(f"    priority={int(entry['priority'])}")
        if entry.get("hidden"):
            block.append("    scan_ssid=1")
        block.append("}")
        lines.append("\n".join(block) + "\n")

    return "\n".join(lines)


def write_supplicant_conf(networks, path, country=None) -> bool:
    """Render and write the config; return whether the content changed.

    Rewriting an identical file would make the caller bounce an association that
    is working, so an unchanged render is reported as no change.
    """
    path = Path(path)
    rendered = render_supplicant_conf(networks, country=country)
    try:
        if path.read_text() == rendered:
            return False
    except OSError:
        pass
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(rendered)
    try:
        # It holds the key to every network this box trusts.
        path.chmod(0o600)
    except OSError:
        log.debug("could not tighten permissions on %s", path, exc_info=True)
    return True
